/** A name from the list, avoiding any already in use where it will be seen. */
export function playerName(taken: Iterable<string> = []): string {
  const used = new Set([...taken].map((n) => n.toLowerCase()));
  for (let i = 0; i < 20; i++) {
    const n = PLAYER_NAMES[Math.floor(Math.random() * PLAYER_NAMES.length)];
    if (!used.has(n.toLowerCase())) return n;
  }
  return PLAYER_NAMES[Math.floor(Math.random() * PLAYER_NAMES.length)];
}

/** A rating for one to show, like a player's: most around the middle of the ladder, a few high. */
export function playerRating(): number {
  const r = (Math.random() + Math.random() + Math.random()) / 3;
  return Math.round(650 + r * 1100);
}
